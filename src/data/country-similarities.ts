/**
 * Get similar countries for a given country slug.
 * Includes both explicit similarities AND reverse links (bidirectional).
 */
export function getSimilarCountries(slug: string): SimilarCountry[] {
  const direct = SIMILARITY_MAP[slug] || [];
  
  // Find reverse links: countries that list this slug as similar
  const reverse: SimilarCountry[] = [];
  const directSlugs = new Set(direct.map(s => s.slug));
  
  for (const [otherSlug, similarities] of Object.entries(SIMILARITY_MAP)) {
    if (otherSlug === slug) continue;
    if (directSlugs.has(otherSlug)) continue; // already in direct list
    
    const match = similarities.find(s => s.slug === slug);
    if (match) {
      reverse.push({ slug: otherSlug, reason: match.reason });
    }
  }
  
  // Combine: direct first, then reverse (up to 5 total)
  return [...direct, ...reverse].slice(0, 5);
}
